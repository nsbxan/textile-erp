export function findPantone(pantoneOrCode) {
  if (!pantoneOrCode) return null;
  const clean = String(pantoneOrCode).trim().toLowerCase();
  return PANTONE_PALETTE.find(
    p => p.pantone.toLowerCase() === clean || p.code.toLowerCase() === clean || p.nameUz.toLowerCase().includes(clean)
  ) || null;
}

export function getPantoneHex(pantoneCode, fallback = '#64748b') {
  const item = findPantone(pantoneCode);
  return item ? item.hex : fallback;
}

export function getPantoneName(pantoneCode, lang = 'lat') {
  const item = findPantone(pantoneCode);
  if (!item) return pantoneCode || '';
  if (lang === 'ru') return item.nameRu;
  if (lang === 'cyr') return item.nameCyr;
  return item.nameUz;
}
